"""
Writer - Final Analysis Generation via DeepSeek
============================================================================
Takes a raw summary from the `summarizer` and polishes it into a
professional, engaging analysis using DeepSeek.

Responsibilities
----------------
- Build the specific prompt for the final analysis.
- Call the DeepSeek API.
- Return the polished text.

Notes
-----
- DeepSeek does NOT calculate. It only writes. The numbers and insights
  come strictly from the `summary` provided by the small models.
- If the API key is missing or the call fails, it returns the original
  summary so the report is never left empty.

Author: Alfonso Droguett
Repository: https://github.com/adroguetth/youtube-music-charts-intelligence
Email: adroguett.consultor@gmail.com
"""

from __future__ import annotations

import os
import requests

# ============================================================================
# PROMPT TEMPLATES
# ============================================================================
WRITER_PROMPTS = {
    "es": (
        "Eres un estratega senior de la industria musical. "
        "Tengo este resumen de datos crudos de la semana:\n\n"
        "{summary}\n\n"
        "Redacta un análisis ejecutivo de 6 líneas. "
        "Reglas estrictas:\n"
        "1. Empieza con una conclusión analítica directa (no con una introducción).\n"
        "2. Conecta los datos con el contexto de la industria (ej. compara el engagement con el promedio del mercado).\n"
        "3. Usa los números exactos del resumen para sustentar tus afirmaciones.\n"
        "4. Termina con una implicación estratégica (ej. 'esto sugiere que la fidelidad pesa más que la viralidad').\n"
        "5. No uses frases de relleno. NO uses notación científica."
    ),
    "en": (
        "You are a senior music industry strategist. "
        "I have this raw data summary for the week:\n\n"
        "{summary}\n\n"
        "Write an executive analysis of 6 lines. "
        "Strict rules:\n"
        "1. Start with a direct analytical conclusion (not an introduction).\n"
        "2. Connect the data with industry context (e.g., compare engagement with market average).\n"
        "3. Use the exact numbers from the summary to support your claims.\n"
        "4. End with a strategic implication (e.g., 'this suggests loyalty weighs more than virality').\n"
        "5. No filler phrases. NO scientific notation."
    )
}


class DeepSeekWriter:
    def __init__(self, api_key: str | None = None):
        self.api_key = api_key or os.environ.get("DEEPSEEK_API_KEY")
        self.api_url = "https://api.deepseek.com/v1/chat/completions"

    def polish(self, summary: str, language: str = "es") -> tuple[str, int]:
        """
        Polish the raw summary using DeepSeek.
        
        Parameters
        ----------
        summary : str
            The raw summary generated by Groq or Gemma.
        language : str
            "es" or "en".

        Returns
        -------
        tuple[str, int]
            (final_text, tokens_used)
        """
        if not summary:
            return "", 0

        if not self.api_key:
            print("   [Writer] DeepSeek API key not found. Using raw summary.")
            return summary, 0

        prompt = WRITER_PROMPTS.get(language, WRITER_PROMPTS["es"]).format(summary=summary)

        try:
            response = requests.post(
                self.api_url,
                headers={
                    "Authorization": f"Bearer {self.api_key}",
                    "Content-Type": "application/json"
                },
                json={
                    "model": "deepseek-chat",
                    "messages": [
                        {"role": "system", "content": "You are an expert music journalist."},
                        {"role": "user", "content": prompt}
                    ],
                    "temperature": 0.6,
                    "max_tokens": 250
                },
                timeout=30
            )
            response.raise_for_status()
            data = response.json()
            
            final_text = data["choices"][0]["message"]["content"].strip()
            tokens_used = data.get("usage", {}).get("total_tokens", 0)
            
            return final_text, tokens_used
            
        except Exception as e:
            print(f"   [Writer] DeepSeek failed: {e}")
            # Fallback: devolver el resumen crudo para no dejar el reporte sin análisis
            print("   [Writer] Falling back to the raw summary.")
            return summary, 0
