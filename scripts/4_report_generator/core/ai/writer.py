"""
Writer - Final Analysis Generation via DeepSeek
============================================================================
Takes a raw summary from the `summarizer` and polishes it into a
professional, engaging analysis using DeepSeek.

Responsibilities
----------------
- Build the specific prompt for the final analysis.
- Call the DeepSeek API.
- Return the polished text.

Notes
-----
- DeepSeek does NOT calculate. It only writes. The numbers and insights
  come strictly from the `summary` provided by the small models.
- If the API key is missing or the call fails, it returns the original
  summary so the report is never left empty.

Author: Alfonso Droguett
Repository: https://github.com/adroguetth/youtube-music-charts-intelligence
Email: adroguett.consultor@gmail.com
"""

from __future__ import annotations

import os
import requests

# ============================================================================
# PROMPT TEMPLATES
# ============================================================================
WRITER_PROMPTS = {
    "es": (
        "Actúa como un periodista de datos musicales de élite, escribiendo para una revista como Billboard o Rolling Stone. "
        "A continuación, te presento un resumen estadístico crudo de la semana:\n\n"
        "{summary}\n\n"
        "Tu tarea es redactar un único párrafo analítico, atractivo y profesional (máximo 4 líneas). "
        "Reglas estrictas:\n"
        "1. Cero alucinaciones: Usa únicamente las cifras exactas que aparecen en el resumen.\n"
        "2. No uses viñetas, listas ni saltos de línea.\n"
        "3. No uses introducciones genéricas como 'Aquí tienes el análisis' o 'En resumen'. Ve directo al grano.\n"
        "4. Comienza con un 'hook' (gancho) periodístico que destaque la tendencia o el dato más sorprendente.\n"
        "5. Mantén un tono dinámico, informativo y persuasivo, como si cerraras un artículo de portada."
    ),
    "en": (
        "Act as an elite music data journalist writing for a top-tier publication like Billboard or Rolling Stone. "
        "Here is a raw statistical summary for the week:\n\n"
        "{summary}\n\n"
        "Your task is to write a single, compelling, and professional analytical paragraph (maximum 4 lines). "
        "Strict rules:\n"
        "1. Zero hallucinations: Use ONLY the exact numbers provided in the summary.\n"
        "2. Do not use bullet points, lists, or line breaks.\n"
        "3. No generic introductory fluff like 'Here is the analysis' or 'In summary'. Get straight to the point.\n"
        "4. Start with a journalistic hook highlighting the most surprising trend or data point.\n"
        "5. Keep a dynamic, informative, and persuasive tone, as if closing a cover story."
    )
}


class DeepSeekWriter:
    def __init__(self, api_key: str | None = None):
        self.api_key = api_key or os.environ.get("DEEPSEEK_API_KEY")
        self.api_url = "https://api.deepseek.com/v1/chat/completions"

    def polish(self, summary: str, language: str = "es") -> tuple[str, int]:
        """
        Polish the raw summary using DeepSeek.
        
        Parameters
        ----------
        summary : str
            The raw summary generated by Groq or Gemma.
        language : str
            "es" or "en".

        Returns
        -------
        tuple[str, int]
            (final_text, tokens_used)
        """
        if not summary:
            return "", 0

        if not self.api_key:
            print("   [Writer] DeepSeek API key not found. Using raw summary.")
            return summary, 0

        prompt = WRITER_PROMPTS.get(language, WRITER_PROMPTS["es"]).format(summary=summary)

        try:
            response = requests.post(
                self.api_url,
                headers={
                    "Authorization": f"Bearer {self.api_key}",
                    "Content-Type": "application/json"
                },
                json={
                    "model": "deepseek-chat",
                    "messages": [
                        {"role": "system", "content": "You are an expert music journalist."},
                        {"role": "user", "content": prompt}
                    ],
                    "temperature": 0.6,
                    "max_tokens": 250
                },
                timeout=30
            )
            response.raise_for_status()
            data = response.json()
            
            final_text = data["choices"][0]["message"]["content"].strip()
            tokens_used = data.get("usage", {}).get("total_tokens", 0)
            
            return final_text, tokens_used
            
        except Exception as e:
            print(f"   [Writer] DeepSeek failed: {e}")
            # Fallback: devolver el resumen crudo para no dejar el reporte sin análisis
            print("   [Writer] Falling back to the raw summary.")
            return summary, 0
